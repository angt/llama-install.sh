import importlib.util
import json
import os
import re
import sys
from pathlib import Path
from urllib.request import Request, urlopen

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, str(Path(__file__).with_name("install")))
import generate

spec = importlib.util.spec_from_file_location("install_clang", Path(__file__).with_name("install") / "clang.py")
install_clang = importlib.util.module_from_spec(spec)
spec.loader.exec_module(install_clang)
CLANG_CUDA_MAX = install_clang.CLANG_CUDA_MAX

with urlopen("https://ziglang.org/download/index.json") as response:
    zig_releases = json.load(response)
zig_releases.pop("master")
zig_version = next(iter(zig_releases))

with urlopen("https://vulkan.lunarg.com/sdk/latest/linux.txt") as response:
    vulkan_version = response.read().decode().strip()

with urlopen("https://nightly.repo.amd.com/rocm/whl-next/rocm/") as response:
    rocm_version = max(
        re.findall(r"rocm-(\d+\.\d+\.\d+a\d+)\.tar\.gz", response.read().decode()),
        key=lambda version: [*map(int, re.findall(r"\d+", version))],
    )

with urlopen("https://developer.download.nvidia.com/compute/cuda/redist/") as response:
    index = response.read().decode()

cuda_versions = {}
for code in sorted(generate.cuda_codes()):
    major = f"{code[:-1]}.{code[-1]}"
    cuda_versions[code] = max(
        re.findall(rf"redistrib_({major}\.[0-9.]+)\.json", index),
        key=lambda version: [*map(int, version.split("."))],
    )

for code in CLANG_CUDA_MAX:
    if code not in cuda_versions:
        sys.exit(f"CLANG_CUDA_MAX has unknown CUDA code '{code}'")
for code in cuda_versions:
    if code not in CLANG_CUDA_MAX:
        sys.exit(f"No clang max set for CUDA {code} - add it to CLANG_CUDA_MAX")


def github_api(url):
    request = Request(url, headers={"User-Agent": "curl/8.0"})
    if token := os.getenv("GITHUB_TOKEN"):
        request.add_header("Authorization", f"Bearer {token}")
    return json.load(urlopen(request))


clang_versions = {}
for major in sorted(set(CLANG_CUDA_MAX.values())):
    refs = github_api(f"https://api.github.com/repos/llvm/llvm-project/git/matching-refs/tags/llvmorg-{major}.")
    finals = [
        match.groups()
        for ref in refs
        for match in [re.fullmatch(r"llvmorg-(\d+)\.(\d+)\.(\d+)", ref["ref"].split("/")[-1])]
        if match
    ]
    if not finals:
        sys.exit(f"No final release found for clang {major}")
    clang_versions[major] = ".".join(max(finals, key=lambda version: [*map(int, version)]))

Path(__file__).with_name("versions.py").write_text(
    "# Generated by scripts/update-ci.py - do not edit.\n"
    f"ZIG_VERSION = {zig_version!r}\n"
    f"VULKAN_VERSION = {vulkan_version!r}\n"
    f"ROCM_VERSION = {rocm_version!r}\n"
    f"CUDA_VERSIONS = {cuda_versions!r}\n"
    f"CLANG_VERSIONS = {clang_versions!r}\n"
)

print(f" - ZIG_VERSION: {zig_version}")
print(f" - VULKAN_VERSION: {vulkan_version}")
print(f" - ROCM_VERSION: {rocm_version}")
for key, value in cuda_versions.items():
    print(f" - CUDA_VERSIONS[{key}]: {value}")
for key, value in CLANG_CUDA_MAX.items():
    print(f" - CLANG_CUDA_MAX[{key}]: {value}")
for key, value in clang_versions.items():
    print(f" - CLANG_VERSIONS[{key}]: {value}")
